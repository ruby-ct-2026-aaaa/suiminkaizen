# frozen_string_literal: true

module Suiminkaizen
  # ゲームバランスに関わる数値をここ一箇所に集約している。
  # 難易度調整はこのファイルだけを触れば済むようにしてある。
  module Config
    # --- 画面 -------------------------------------------------------------
    # 論理解像度 320x240 のドット絵を SCALE 倍して表示する。
    # 全ての描画は論理座標で行い、最後に整数丸め→拡大するのでドットが崩れない。
    SCALE    = 3
    W        = 320
    H        = 240
    SCREEN_W = W * SCALE
    SCREEN_H = H * SCALE
    CAPTION  = "睡眠改善プロジェクト 〜ショートスリーパー峰小輔の一週間〜"

    # --- 睡眠ゲージ -------------------------------------------------------
    MAX_GAUGE      = 1000.0 # ここまで貯まると気絶（ゲームオーバー）
    START_GAUGE    =    0.0 # 0 が通常＝健康
    SLEEP_RECOVERY =   30.0 # 1日の終わりの「30分睡眠」で減る量
    TOTAL_DAYS     =      7

    # --- 1日の構成 --------------------------------------------------------
    # 6本 x (説明 約4s + 本編 42s + リザルト 約5s) + 朝夕の演出 ≒ 5分/日。
    # 7日クリアでおよそ 35 分になる。
    GAMES_PER_DAY    = 6
    MINIGAME_SECONDS = 42.0

    # 達成率の上限。目標スコアを超えた分もある程度ボーナスになる。
    MAX_PERFORMANCE = 1.2

    module_function

    # 1秒あたりに溜まる眠気。日が進むほど身体は限界に近づく。
    #   day1: 1.35/s ... day7: 2.04/s
    # 「達成率0.8＋1日あたり200程度のミス」でじりじり増えていく（＝7日目に
    # 残り半分くらいまで追い詰められる）ように逆算した値。
    def drowsiness_rate(day)
      1.35 + 0.115 * (day - 1)
    end

    # ミニゲーム外（説明・リザルト・朝夕の演出）はゆるやかに溜まる。
    def idle_rate(day)
      drowsiness_rate(day) * 0.6
    end

    # ミニゲーム1本を完璧にこなしたときに削れるゲージの上限。
    #   day1: 100 ... day7: 148
    # 「成功難易度に応じて削減量が可変」の外枠にあたる部分。
    def max_reward(day)
      100.0 * (1.0 + 0.08 * (day - 1))
    end

    # ミニゲームの速度・判定の厳しさ倍率。
    def difficulty(day)
      1.0 + 0.12 * (day - 1)
    end

    # 世界座標の奥行きから描画順(z)を決める。手前ほど大きい値＝後から描かれる。
    def depth_z(world_z)
      60.0 - world_z * 2.0
    end
  end
end
